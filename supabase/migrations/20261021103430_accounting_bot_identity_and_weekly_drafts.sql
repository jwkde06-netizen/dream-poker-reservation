-- Additive rollout: the deployed legacy handler keeps its update_id key and
-- tables. Dedicated accounting bot events have their own bot/update namespace.
begin;

create table if not exists public.dream_accounting_jobs_v2 (
  bot_id text not null check (bot_id ~ '^[0-9]+$'),
  update_id bigint not null check (update_id >= 0),
  chat_id text not null check (chat_id ~ '^-[0-9]+$'),
  message_id bigint not null,
  sender_id text not null,
  text text not null,
  status text not null default 'received',
  image_key text,
  plan jsonb,
  reply_text text,
  reply_id bigint,
  failure_reason text,
  created_at timestamptz not null default now(),
  primary key (bot_id, update_id)
);
create index if not exists dream_accounting_jobs_v2_message on public.dream_accounting_jobs_v2(chat_id, message_id);
create index if not exists dream_accounting_jobs_v2_reply on public.dream_accounting_jobs_v2(chat_id, reply_id);
create index if not exists dream_accounting_jobs_v2_image on public.dream_accounting_jobs_v2(image_key) where status='applied';
alter table public.dream_accounting_jobs_v2 enable row level security;
revoke all on public.dream_accounting_jobs_v2 from public, anon, authenticated;
grant select, insert, update on public.dream_accounting_jobs_v2 to service_role;

create table if not exists public.dream_accounting_rules_v2 (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('instruction','table_round_labels')),
  content text not null check (length(content) between 1 and 800),
  source_text text not null,
  source_bot_id text not null,
  source_update bigint,
  source_chat_id text,
  sender_id text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (source_bot_id, source_update)
);
alter table public.dream_accounting_rules_v2 enable row level security;
revoke all on public.dream_accounting_rules_v2 from public, anon, authenticated;
grant select, insert, update on public.dream_accounting_rules_v2 to service_role;
grant usage, select on sequence public.dream_accounting_rules_v2_id_seq to service_role;

-- Preserve the existing business rules and their human-visible numbers. Apply
-- this migration immediately before cutover; later legacy teaching is not copied
-- automatically or allowed to overwrite rules taught to the dedicated bot.
do $$
begin
  if to_regclass('public.dream_accounting_rules') is not null then
    insert into public.dream_accounting_rules_v2
      (id,kind,content,source_text,source_bot_id,source_update,source_chat_id,sender_id,active,created_at)
    select id,kind,content,source_text,'legacy',source_update,null,sender_id,active,created_at
      from public.dream_accounting_rules
    on conflict do nothing;
  end if;
end;
$$;
select setval(pg_get_serial_sequence('public.dream_accounting_rules_v2','id'),
  greatest(coalesce((select max(id) from public.dream_accounting_rules_v2),1),1),
  exists(select 1 from public.dream_accounting_rules_v2));

create table if not exists public.dream_accounting_evidence (
  id bigint generated always as identity primary key,
  bot_id text not null,
  update_id bigint not null,
  chat_id text not null,
  message_id bigint not null,
  sender_id text not null,
  business_date date not null,
  source text not null check (source in ('viber','cashier')),
  reference text not null check (length(reference) between 1 and 500),
  totals jsonb not null check (jsonb_typeof(totals)='object'),
  image_key text,
  source_text text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (bot_id, update_id)
);
create index if not exists dream_accounting_evidence_period on public.dream_accounting_evidence(chat_id,business_date) where active;
alter table public.dream_accounting_evidence enable row level security;
revoke all on public.dream_accounting_evidence from public, anon, authenticated;
grant select, insert, update on public.dream_accounting_evidence to service_role;
grant usage, select on sequence public.dream_accounting_evidence_id_seq to service_role;

create table if not exists public.dream_accounting_reports (
  id uuid primary key default gen_random_uuid(),
  period_start date not null,
  period_end date not null,
  chat_id text not null,
  created_by text not null,
  event_key text unique,
  workbook_id text not null,
  recipient_label text not null default '김지영 대표',
  status text not null check (status in ('needs_review','ready_for_review')),
  draft jsonb not null check (jsonb_typeof(draft)='object'),
  created_at timestamptz not null default now(),
  check (period_end >= period_start and period_end - period_start <= 30)
);
create index if not exists dream_accounting_reports_period on public.dream_accounting_reports(chat_id,period_start,period_end);
alter table public.dream_accounting_reports enable row level security;
revoke all on public.dream_accounting_reports from public, anon, authenticated;
grant select, insert on public.dream_accounting_reports to service_role;

commit;
