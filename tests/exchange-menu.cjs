// Run after compiling app/api/exchange/{webhook,diagnostics}/route.ts to EXCHANGE_TEST_BUILD.
const assert = require('node:assert/strict');
const path = require('node:path');
const root = process.env.EXCHANGE_TEST_BUILD || path.resolve(__dirname, '../.test-build');
const load = file => require(path.join(root, file));
const settings = load('lib/exchange-settings.js');
const telegram = load('lib/exchange-telegram.js');
const agent = load('lib/exchange-agent.js');
const admin = load('lib/telegram.js');
const menu = load('lib/exchange-menu.js');
const token = '123456:OFFLINE_FAKE_TOKEN_ONLY_123456';
const config = { token, chatId: '-1001', botId: '123456', activatedAt: 1, adminIds: new Set() };
let calls = [], menuFailure = '', failure = '', mismatch = false, ledgerCalls = 0;
global.fetch = async (url, options) => {
  const method = url.split('/').at(-1), payload = JSON.parse(options.body);
  calls.push({ method, payload });
  if (method === 'setMyCommands' && menuFailure) return { ok: false, status: 429, json: async () => ({ ok: false, description: 'RAW_SECRET' }) };
  if (failure === 'network') throw Error('RAW_SECRET_URL_' + url);
  if (failure === 'json') return { ok: true, status: 200, json: async () => { throw Error('RAW_SECRET'); } };
  if (failure === 'api') return { ok: false, status: 429, json: async () => ({ ok: false, description: 'RAW_SECRET' }) };
  let result = true;
  if (method === 'getMyCommands') result = mismatch ? [] : menu.EXCHANGE_COMMANDS;
  if (method === 'getChatMember') result = { status: 'administrator' };
  if (method === 'getMe') result = { id: 123456, username: settings.EXPECTED_EXCHANGE_USERNAME, is_bot: true };
  if (method === 'getWebhookInfo') result = { url: settings.EXCHANGE_PUBLIC_URL + '/api/exchange/webhook' };
  return { ok: true, status: 200, json: async () => ({ ok: true, result }) };
};
(async () => {
  const infoLogs = [], originalInfo = console.info;
  console.info = (...args) => infoLogs.push(args);
  await menu.ensureCommandMenu(false, config);
  assert.deepEqual(calls.map(c => c.method), ['setMyCommands', 'setMyCommands', 'getMyCommands', 'getMyCommands']);
  assert(calls.every(c => c.payload.scope.type === 'chat' && c.payload.scope.chat_id === '-1001'));
  assert.equal(calls[1].payload.language_code, 'ko');
  assert.deepEqual(infoLogs, [['exchange_menu_verified', { menuVersion: menu.EXCHANGE_MENU_VERSION, commandCount: menu.EXCHANGE_COMMANDS.length }]]);
  for (const command of ['krwin', 'fx', 'in', 'out', 'expense', 'profit', 'loss', 'opening', 'cancel']) {
    assert(menu.EXCHANGE_COMMANDS.some(c => c.command === command), command + ' must be registered');
  }
  assert(menu.EXCHANGE_COMMANDS.every(c => c.description.length <= 256));
  assert(!menu.EXCHANGE_COMMANDS.find(c => c.command === 'help').description.includes('+5만'));
  assert.equal(menu.EXCHANGE_MENU_VERSION, 'exchange-menu-20261109-v3');
  await menu.ensureCommandMenu(false, config); assert.equal(calls.length, 4);
  await menu.ensureCommandMenu(true, config); assert.equal(calls.length, 8);
  await menu.ensureCommandMenu(false, { ...config, chatId: '-1002' }); assert.equal(calls.length, 12);
  await menu.ensureCommandMenu(false, { ...config, token: '999999:OFFLINE_FAKE_TOKEN_ONLY_123456' }); assert.equal(calls.length, 16);
  mismatch = true;
  const beforeMismatchLogs = infoLogs.length;
  await assert.rejects(menu.ensureCommandMenu(true, config), /verification failed/);
  assert.equal(infoLogs.length, beforeMismatchLogs, 'mismatching readback cannot emit success');
  mismatch = false; calls = [];
  await menu.ensureCommandMenu(false, config); assert.equal(calls.length, 4, 'failed force must clear old success cache');
  for (const kind of ['network', 'json', 'api']) {
    failure = kind;
    const beforeFailureLogs = infoLogs.length;
    await assert.rejects(menu.ensureCommandMenu(true, config));
    assert.equal(infoLogs.length, beforeFailureLogs, 'API failure cannot emit success');
    await assert.rejects(settings.setupTelegram(token, 'getMyCommands'), error => error instanceof settings.TelegramSetupFailure && !JSON.stringify(error).includes('RAW_SECRET') && !error.stack.includes(token));
  }
  failure = '';
  settings.loadExchangeSettings = async () => ({ enabled: true, chat_id: config.chatId, activated_at: '1970-01-01T00:00:01Z' });
  settings.runtimeFromSettings = () => ({ token, secret: 'offline-secret', username: settings.EXPECTED_EXCHANGE_USERNAME, chatId: config.chatId, adminIds: [], activatedAt: '1970-01-01T00:00:01Z', enabled: true });
  settings.pairExchangeRoom = async () => false;
  telegram.exchangeConfig = () => config;
  telegram.exchangeAuthorized = request => request.headers.get('x-telegram-bot-api-secret-token') === 'offline-secret';
  agent.handleExchangeUpdate = async () => { ledgerCalls++; };
  const route = load('app/api/exchange/webhook/route.js');
  process.env.VERCEL_ENV = 'production';
  const request = (text, extra = {}) => new Request('https://offline.invalid', { method: 'POST', headers: { 'x-telegram-bot-api-secret-token': 'offline-secret' }, body: JSON.stringify({ message: { text, chat: { id: -1001 }, from: { id: 7 }, date: 10, message_id: 4, ...extra } }) });
  calls = [];
  assert.equal((await route.POST(request('/commands'))).status, 200);
  assert.equal(calls.filter(c => c.method === 'setMyCommands').length, 2, 'commands forces even warm cache');
  assert(calls.find(c => c.method === 'sendMessage').payload.text.includes('등록·확인 완료'));
  assert.equal(ledgerCalls, 0);
  calls = []; mismatch = true;
  const logs = [], originalError = console.error;
  console.error = (...args) => logs.push(args);
  assert.equal((await route.POST(request('/commands'))).status, 200);
  assert(calls.find(c => c.method === 'sendMessage').payload.text.includes('확인하지 못했습니다'));
  assert.equal((await route.POST(request('ordinary message'))).status, 200);
  assert.equal(ledgerCalls, 1, 'menu failure must not block ledger handler');
  calls = []; mismatch = false; menuFailure = 'api';
  assert.equal((await route.POST(request('/commands'))).status, 200);
  assert(calls.find(c => c.method === 'sendMessage').payload.text.includes('확인하지 못했습니다'));
  assert.equal((await route.POST(request('ordinary after API failure'))).status, 200);
  assert.equal(ledgerCalls, 2);
  assert(logs.some(entry => entry[1]?.method === 'setMyCommands' && entry[1]?.status === 429));
  menuFailure = ''; calls = [];
  await route.POST(request('/commands', { forward_date: 5 }));
  await route.POST(request('/commands', { via_bot: { id: 9 } }));
  await route.POST(request('/commands', { date: 0 }));
  assert.equal(calls.length, 0, 'untrusted/stale commands cannot mutate menus');
  const publicData = await (await route.GET()).json();
  assert.deepEqual(Object.keys(publicData).sort(), ['commands', 'version']);
  assert(publicData.commands.includes('krwin'));
  const diagnostics = load('app/api/exchange/diagnostics/route.js');
  admin.requireAdmin = async () => null;
  assert.equal((await diagnostics.GET(new Request('https://offline.invalid'))).status, 403);
  assert.equal((await diagnostics.POST(new Request('https://offline.invalid'))).status, 403);
  assert.equal(calls.length, 0);
  admin.requireAdmin = async () => ({ id: 'offline-admin' });
  settings.withSavedExchange = async fn => fn({ enabled: true });
  mismatch = false;
  assert.equal((await diagnostics.GET(new Request('https://offline.invalid'))).status, 200);
  assert(calls.every(c => ['getMe','getWebhookInfo','getMyCommands'].includes(c.method)), 'diagnostic GET is read-only');
  calls = [];
  assert.equal((await diagnostics.POST(new Request('https://offline.invalid'))).status, 200);
  assert.equal(calls.filter(c => c.method === 'setMyCommands').length, 2);
  console.error = originalError;
  assert(!JSON.stringify(logs).includes(token));
  assert(!JSON.stringify(infoLogs).includes(token));
  assert(infoLogs.every(entry => entry[0] === 'exchange_menu_verified' && Object.keys(entry[1]).sort().join(',') === 'commandCount,menuVersion'));
  console.info = originalInfo;
  console.log('exchange menu: readback, forced refresh, scoped cache, safe failures, real route dispatch and authenticated diagnostics PASS');
})().catch(error => { console.error(error); process.exitCode = 1; });
