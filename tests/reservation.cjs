const assert=require('node:assert/strict');
const {reservationCapacity,validateReservationAction,parseReservationCommand}=require('../.test-build/reservation-domain');
const {eligibleReservationUpdate}=require('../.test-build/reservation-agent');
const game='11111111-1111-4111-8111-111111111111';
assert.deepEqual(reservationCapacity(3,0,3,0),{newSeatCapacity:3,returning:6,confirmed:0,held:3,allocatedPending:0,unheld:0,replaceable:3,overCapacity:false});
assert.equal(reservationCapacity(3,1,1,1).overCapacity,false);
assert.throws(()=>validateReservationAction({kind:'holds',game_id:game,count:4}));
assert.throws(()=>validateReservationAction({kind:'book',game_id:game,name:'LEE DAE JIN',arrival_at:'2026-10-21T12:00:00Z'}));
assert.equal(parseReservationCommand(`/carryover ${game} 6`).count,6);
assert.equal(parseReservationCommand(`/book ${game} TEST PLAYER | 19:30`,new Date('2026-10-21T09:00:00Z')).arrival_at,'2026-10-21T12:30:00.000Z');
assert.equal(parseReservationCommand('지금 6명인 것 같은데'),null);
const config={enabled:true,chatId:'-100000001'};
const update={update_id:1,message:{message_id:1,date:1792569600,text:'/games',chat:{id:-100000001,type:'group'},from:{id:123,is_bot:false}}};
assert.equal(eligibleReservationUpdate(update,config),true);
assert.equal(eligibleReservationUpdate({...update,message:{...update.message,sender_chat:{id:123}}},config),false);
assert.equal(eligibleReservationUpdate({...update,message:{...update.message,forward_origin:{type:'user'}}},config),false);
assert.equal(eligibleReservationUpdate({...update,edited_message:update.message},config),false);
assert.equal(eligibleReservationUpdate({...update,message:{...update.message,chat:{id:-100000002,type:'group'}}},config),false);
assert.equal(eligibleReservationUpdate(update,{...config,enabled:false}),false);
console.log('Reservation domain and Telegram scope tests passed');
