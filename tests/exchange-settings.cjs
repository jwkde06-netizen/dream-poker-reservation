const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const { randomBytes } = require('node:crypto');
const settings = require('../.test-build/exchange-settings');
const telegram = require('../.test-build/exchange-telegram');
(async () => {
  process.env.EXCHANGE_SETTINGS_KEY = randomBytes(32).toString('hex');
  const token = '100001:abcdefghijklmnopqrstuvwxyz123456';
  const secret = randomBytes(32).toString('hex');
  const encrypted = settings.sealCredentials(token, secret);
  assert.equal(encrypted.includes(token), false);
  assert.deepEqual(settings.openCredentials(encrypted), { token, secret });
  assert.notEqual(settings.sealCredentials(token, secret), encrypted);
  const parts = encrypted.split('.'); parts[2] = Buffer.alloc(16).toString('base64url');
  assert.throws(() => settings.openCredentials(parts.join('.')));
  const key = process.env.EXCHANGE_SETTINGS_KEY;
  process.env.EXCHANGE_SETTINGS_KEY = randomBytes(32).toString('hex');
  assert.throws(() => settings.openCredentials(encrypted)); process.env.EXCHANGE_SETTINGS_KEY = key;
  const runtime = { token, secret, username: 'dream_poker_exchange_bot', chatId: '-100001', adminIds: ['200001'], activatedAt: '2026-10-21T00:00:00Z', enabled: true };
  await Promise.all(['-100001', '-100002'].map(chatId => settings.exchangeRuntime.run({ ...runtime, chatId }, async () => { await new Promise(r => setTimeout(r, 5)); assert.equal(telegram.exchangeConfig().chatId, chatId); assert.equal(telegram.exchangeAuthorized(new Request('https://example.invalid', { headers: { 'x-telegram-bot-api-secret-token': secret } })), true); })));
  assert.equal(settings.exchangeRuntime.getStore(), undefined);
  assert.equal(telegram.exchangeAuthorized(new Request('https://example.invalid')), false);
  let network = 0; const prior = global.fetch;
  global.fetch = async () => { network++; throw Error('Rejected pairing must not call network'); };
  const code = 'a'.repeat(32), row = { chat_id: null, pair_hash: settings.hashPairCode(code), pair_expires_at: new Date(Date.now() + 60000).toISOString(), activated_at: '2026-10-21T00:00:00Z' };
  const message = { text: '/connect@dream_poker_exchange_bot ' + code, chat: { id: -100001, type: 'group' }, from: { id: 200001, is_bot: false }, date: Math.floor(Date.now()/1000) };
  assert.equal(await settings.pairExchangeRoom({ message: { ...message, from: { id: 200001, is_bot: true } } }, row), true);
  assert.equal(await settings.pairExchangeRoom({ message }, { ...row, pair_hash: 'b'.repeat(64) }), true);
  assert.equal(await settings.pairExchangeRoom({ message }, { ...row, pair_expires_at: '2020-01-01T00:00:00Z' }), true);
  assert.equal(await settings.pairExchangeRoom({ message }, { ...row, chat_id: '-100002' }), true);
  assert.equal(network, 0); global.fetch = prior;
  const db = new PGlite();
  try {
    await db.exec('create role anon; create role authenticated; create role service_role bypassrls;');
    await db.exec(fs.readFileSync('supabase/exchange_connection.sql', 'utf8'));
    await db.exec('set role service_role');
    await db.query("insert into public.dream_exchange_connection(bot_id,username,encrypted_credentials,pair_hash,pair_expires_at) values('100001','dream_poker_exchange_bot','synthetic',$1,now()+interval '15 minutes')", [settings.hashPairCode(code)]);
    const bind = async hash => (await db.query("select public.dream_exchange_bind_room($1,'-100001','Synthetic room','200001') ok", [hash])).rows[0].ok;
    assert.equal(await bind(settings.hashPairCode(code)), false);
    await db.exec('update public.dream_exchange_connection set webhook_verified=true;');
    assert.equal(await bind('b'.repeat(64)), false);
    assert.equal(await bind(settings.hashPairCode(code)), true);
    assert.equal(await bind(settings.hashPairCode(code)), false);
    const state = (await db.query('select enabled,chat_id,admin_ids,pair_hash,pair_expires_at from public.dream_exchange_connection')).rows[0];
    assert.equal(state.enabled, true); assert.equal(state.chat_id, '-100001'); assert.equal(state.pair_hash, null); assert.equal(state.pair_expires_at, null); assert.deepEqual(state.admin_ids, ['200001']);
    await db.exec('reset role; set role anon;');
    await assert.rejects(() => db.query('select * from public.dream_exchange_connection'));
    await assert.rejects(() => bind(settings.hashPairCode(code)));
  } finally { await db.close(); }
  console.log('exchange settings: encryption, tamper rejection, request isolation, pairing authorization, one-use binding and anonymous denial passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
