const assert=require('node:assert/strict');
const {needsChipVerification,verifyChipEvidence}=require('../.test-build/accounting-vision');
const op={kind:'total',date:'2026-10-21',game:6,table:5,player:'CHANG YOON HO',buyins:1};
const rules=[{content:'CHANG CALEB YOON-HO = CHANG YOON HO'}];
const evidence={names:['ANOTHER PLAYER','CHANG CALEB YOON-HO','LAST PLAYER'],chipAmounts:[100000,200000,100000]};
let result=verifyChipEvidence([op],evidence,rules);
assert.equal(result.operations.length,0);assert.match(result.questions[0],/CHANG YOON HO/);
result=verifyChipEvidence([{...op,buyins:2}],evidence,rules);
assert.equal(result.operations[0].chips,200000);assert.equal(result.questions.length,0);
assert.equal(verifyChipEvidence([{...op,buyins:2}],evidence,[]).operations.length,0);
const two=[op,{...op,player:'LAST PLAYER'}];
assert.deepEqual(verifyChipEvidence(two,evidence,rules).operations.map(x=>x.player),['LAST PLAYER']);
assert.equal(verifyChipEvidence(two,{names:evidence.names,chipAmounts:[100000]},rules).operations.length,0);
assert.equal(verifyChipEvidence([op],{names:['CHANG YOON HO','CHANG YOON HO'],chipAmounts:[100000,100000]},rules).operations.length,0);
assert.equal(verifyChipEvidence([op],{names:['CHANG YOON HO'],chipAmounts:['100000']},rules).operations.length,0);
assert.equal(verifyChipEvidence([op],{names:['CHANG YOON HO'],chipAmounts:[150000]},rules).operations.length,0);
const daily=[['NUMBER'],[6,46316,'5-2','5M','CHANG YOON HO','','',1]];
assert(needsChipVerification([op],daily));
assert(!needsChipVerification([{...op,game:12}],daily));
assert(!needsChipVerification([{...op,table:13}],daily));
assert(!needsChipVerification([{kind:'fnb'}],daily));
console.log('Independent chip-column verification and partial withholding passed');

const {confirmChipCount}=require('../.test-build/accounting-vision');
const pending={plan:{unverifiedOperations:[op],pendingQuestion:'CHANG YOON HO님 사진의 누적 바이인 수만 확인해주세요.'}};
assert.equal(confirmChipCount('2바인',pending).buyins,2);
assert.equal(confirmChipCount('총 2바인',pending).chips,200000);
assert.equal(confirmChipCount('0바인',pending),null);
assert.equal(confirmChipCount('2바인 추가',pending),null);
assert.equal(confirmChipCount('2바인',{plan:{...pending.plan,pendingQuestion:'사진의 누적 바이인 수를 확인해주세요.'}}),null);
assert.equal(confirmChipCount('2바인',{plan:{...pending.plan,unverifiedOperations:[op,op]}}),null);
console.log('Short cumulative-count reply resolves only the named withheld item');

const {withheldChipOperations,continueChipConfirmation}=require('../.test-build/accounting-vision');
const other={...op,player:'OTHER PLAYER'},already={...op,player:'VERIFIED PLAYER'};
assert.deepEqual(withheldChipOperations([op,other,already],[already]),[op,other]);
const first={plan:{unverifiedOperations:[op,other],pendingQuestion:'CHANG YOON HO님 사진의 누적 바이인 수만 확인해주세요.'}};
const resumed=continueChipConfirmation('2',first);
assert.equal(resumed.operations[0].buyins,2);
assert.deepEqual(resumed.unverifiedOperations,[other]);
assert.equal(resumed.question,'OTHER PLAYER님은 총 몇 바인인가요?');
const second=continueChipConfirmation('3바인',{plan:{...resumed,pendingQuestion:resumed.question}});
assert.equal(second.operations[0].player,'OTHER PLAYER');assert.equal(second.operations[0].buyins,3);assert.equal(second.question,null);assert.deepEqual(second.unverifiedOperations,[]);
assert.equal(continueChipConfirmation('2',{plan:{...first.plan,pendingQuestion:'카드 번호는 무엇인가요?'}}),null);
assert.equal(continueChipConfirmation('2바인 추가',first),null);
console.log('Multiple withheld players resume one-by-one without replaying verified players');
