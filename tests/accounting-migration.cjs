const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {PGlite}=require('@electric-sql/pglite');

(async()=>{
  const db=new PGlite();
  try {
    await db.exec(`
      create role anon;
      create role authenticated;
      create role service_role bypassrls;
      create table public.dream_accounting_jobs(update_id bigint primary key,status text);
      insert into public.dream_accounting_jobs values(77,'applied');
      create table public.dream_accounting_rules(
        id bigint generated by default as identity primary key,kind text,content text,source_text text,
        source_update bigint unique,sender_id text,active boolean,created_at timestamptz default now()
      );
      insert into public.dream_accounting_rules(kind,content,source_text,source_update,sender_id,active)
      values('instruction','테스트 업무 규칙','test',7,'test-operator',true);
    `);
    const file=fs.readdirSync(path.join(__dirname,'../supabase/migrations')).find(name=>name.endsWith('_accounting_bot_identity_and_weekly_drafts.sql'));
    assert(file);
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations',file),'utf8'));
    // The currently deployed legacy upsert remains valid after an additive migration.
    await db.exec(`insert into public.dream_accounting_jobs values(77,'review') on conflict(update_id) do update set status=excluded.status`);
    assert.equal((await db.query('select status from public.dream_accounting_jobs where update_id=77')).rows[0].status,'review');
    assert.equal((await db.query('select content from public.dream_accounting_rules_v2 where id=1')).rows[0].content,'테스트 업무 규칙');
    await db.exec(`insert into public.dream_accounting_jobs_v2(bot_id,update_id,chat_id,message_id,sender_id,text) values
      ('100001',42,'-1000000001',1,'operator','first'),('200002',42,'-1000000001',2,'operator','second')`);
    assert.equal((await db.query('select count(*)::int as count from public.dream_accounting_jobs_v2')).rows[0].count,2);
    await db.exec(`insert into public.dream_accounting_rules_v2(kind,content,source_text,source_bot_id,source_update,sender_id) values
      ('instruction','새 테스트 규칙','test','100001',7,'operator')`);
    assert.equal((await db.query('select max(id)::int as id from public.dream_accounting_rules_v2')).rows[0].id,2,'copied rule IDs must not collide with the identity sequence');
    for(const table of ['dream_accounting_jobs_v2','dream_accounting_rules_v2','dream_accounting_evidence','dream_accounting_reports']){
      const result=await db.query("select relrowsecurity as rls,has_table_privilege('anon',$1,'SELECT') as anon_read,has_table_privilege('authenticated',$1,'SELECT') as user_read,has_table_privilege('service_role',$1,'SELECT') as service_read from pg_class where oid=$1::regclass",['public.'+table]);
      assert.deepEqual(result.rows[0],{rls:true,anon_read:false,user_read:false,service_read:true});
    }
    console.log('Accounting additive migration, copied rules, cross-bot keys and access checks passed');
  } finally {await db.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
