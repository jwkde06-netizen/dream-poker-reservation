assert.throws(()=>summarizeDay([[],row(1,'A',1,'#REF!')],'2026-10-22'),/확인/);
assert.throws(()=>summarizeDay(rows,'2026-02-30'),/날짜/);
assert.throws(()=>summarizeDay(rows,'2026-10-23'),/없어요/);
